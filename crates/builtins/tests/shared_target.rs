//! R196: two worktrees sharing one `CARGO_TARGET_DIR` each build their own built-in guests.
//!
//! Cargo keys a package's build directory by name and version, not by path, so the second tree to
//! build reads the first tree's `OUT_DIR` — and the guests' bytes, their nested cargo's target dir
//! and the build script's watch list all live there. Each step below is one way that shows up.
//!
//! The fixture is this repository in miniature: a host crate whose `build.rs` is the real one
//! (`include_str!`), and one guest under `plugins/builtin`, so the layout the script derives from
//! `CARGO_MANIFEST_DIR` is the layout it finds here. The guest's marker rides in the module's data
//! section, and the host prints the module it embedded, so the assertion is on the bytes the build
//! put in the binary rather than on the script's output.

use std::path::{Path, PathBuf};
use std::process::Command;

/// The build script under test, byte for byte: a fixture copy of it would be a second thing to fix,
/// and the copy is what the test would then be proving.
const BUILD_RS: &str = include_str!("../build.rs");

/// A guest's sources as this fixture's one layer: a dependency-free `cdylib` for the guest target.
const GUEST: &str = "\
[package]
name = \"letibot-builtin-tiny\"
version = \"0.1.0\"
edition = \"2021\"
publish = false

[workspace]

[lib]
crate-type = [\"cdylib\"]
";

/// A guest with no dependencies has a lock with one entry, and this repository keeps its guests'
/// locks in the tree — so the fixture has one too, or a missing watched path would make the script
/// re-run for that reason instead of the one each step is about.
const GUEST_LOCK: &str = "\
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = \"letibot-builtin-tiny\"
version = \"0.1.0\"
";

/// The host crate: a `Builtin`-shaped struct the generated table can name, then the table itself,
/// then a `main` that writes the module it carries to stdout and nothing else — the manifest is
/// `include_str!`ed too, and a marker in it would answer for the module.
const HOST_MAIN: &str = "\
pub struct Builtin {
    pub name: &'static str,
    pub manifest: &'static str,
    pub wasm: &'static [u8],
}

include!(concat!(env!(\"OUT_DIR\"), \"/table.rs\"));

fn main() {
    use std::io::Write;
    let mut out = std::io::stdout();
    for b in table() {
        let _ = out.write_all(b.wasm);
        println!(\"{}\", b.name);
    }
}
";

#[test]
fn a_second_tree_builds_its_own_guest_into_a_shared_target_dir() {
    let root = scratch("letibot-builtins-shared-target");
    let target = root.join("target");
    let a = root.join("a");
    let b = root.join("b");
    tree(&a, "from-a");
    tree(&b, "from-b");

    // The first build is the one that owns the shared directory: it is right, and it is what the
    // steps below must not be answered by.
    let out = build(&a, &target);
    assert!(
        out.contains("from-a"),
        "tree a should carry its own guest: {out}"
    );
    assert!(
        !out.contains("from-b"),
        "tree a built tree b's guest: {out}"
    );

    // A watched file in B that is not a guest's source: B's script has to re-run, and the guest it
    // then keeps has to be B's — the shared guest target dir said B's sources were older than A's.
    write(
        &b.join("plugins/builtin/tiny/plugin.toml"),
        &manifest("touched"),
    );
    let out = build(&b, &target);
    assert!(
        out.contains("from-b"),
        "tree b built tree a's guest: its own guest directory is not the one it built: {out}"
    );

    // The row's bar: a guest changed in B after A was built, B built with the same target dir.
    guest(&b, "from-b-changed");
    let out = build(&b, &target);
    assert!(
        out.contains("from-b-changed"),
        "tree b embedded the guest it was built from before the change: {out}"
    );

    // And the other direction, so this is not a fix that only ever lets the last tree through.
    guest(&a, "from-a-changed");
    let out = build(&a, &target);
    assert!(
        out.contains("from-a-changed"),
        "tree a embedded the guest of the tree that built last: {out}"
    );

    let _ = std::fs::remove_dir_all(&root);
}

/// One tree of the fixture, complete before any build: its guest's sources are older than the
/// other tree's build, which is the ordering a fresh fix must not depend on.
fn tree(dir: &Path, marker: &str) {
    write(
        &dir.join("Cargo.toml"),
        "[workspace]\nresolver = \"3\"\nmembers = [\"crates/host\"]\nexclude = [\"plugins\"]\n",
    );
    write(
        &dir.join("crates/host/Cargo.toml"),
        "[package]\nname = \"host\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    );
    write(&dir.join("crates/host/build.rs"), BUILD_RS);
    write(&dir.join("crates/host/src/main.rs"), HOST_MAIN);
    // The build script watches the guests' shared path dependency; the fixture has to hold one, or
    // the watch would be of a path that is never there.
    write(&dir.join("crates/plugin-sdk/src/lib.rs"), "");
    write(&dir.join("plugins/builtin/tiny/Cargo.toml"), GUEST);
    write(&dir.join("plugins/builtin/tiny/Cargo.lock"), GUEST_LOCK);
    write(
        &dir.join("plugins/builtin/tiny/plugin.toml"),
        &manifest("first"),
    );
    guest(dir, marker);
}

/// The guest's sources: the marker is a string literal an exported function hands out, so the
/// module keeps it in its data section and the host's stdout shows which build it came from.
fn guest(dir: &Path, marker: &str) {
    write(
        &dir.join("plugins/builtin/tiny/src/lib.rs"),
        &format!(
            "const MARKER: &str = \"{marker}\";\n\n\
             #[no_mangle]\n\
             pub extern \"C\" fn marker() -> *const u8 {{\n    \
             MARKER.as_ptr()\n}}\n"
        ),
    );
}

fn manifest(note: &str) -> String {
    format!("name = \"tiny\"\nhooks = [\"pane_tiny\"]\nnote = \"{note}\"\n")
}

/// Build one tree into the shared target dir and answer what its binary carries. A failed build is
/// the assertion: what it printed is the only useful thing about it.
fn build(tree: &Path, target: &Path) -> String {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let built = Command::new(cargo)
        .current_dir(tree)
        .env("CARGO_TARGET_DIR", target)
        // The guest's own build is a nested cargo under this one, so the outer build's environment
        // has to be the plain one: a wrapper, a lint level or a jobserver fd would be its build.
        .env_remove("CARGO_BUILD_TARGET")
        .env_remove("CARGO_BUILD_TARGET_DIR")
        .env_remove("RUSTFLAGS")
        .env_remove("CARGO_ENCODED_RUSTFLAGS")
        .env_remove("RUSTC_WRAPPER")
        .env_remove("RUSTC_WORKSPACE_WRAPPER")
        .env_remove("CARGO_MAKEFLAGS")
        .env_remove("MAKEFLAGS")
        .args(["build", "--offline"])
        .output()
        .expect("run cargo in the fixture");
    assert!(
        built.status.success(),
        "the fixture's build failed in {}: {}",
        tree.display(),
        String::from_utf8_lossy(&built.stderr)
    );
    let run = Command::new(target.join("debug/host"))
        .output()
        .expect("run the fixture's binary");
    assert!(run.status.success(), "the fixture's binary failed");
    String::from_utf8_lossy(&run.stdout).into_owned()
}

fn write(path: &Path, body: &str) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("create a fixture directory");
    }
    std::fs::write(path, body).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

/// A fixture root no other run can be holding: the process id alone is not enough, because a test
/// binary inside a boundary has the same pid every time and a killed run's leftovers would be this
/// run's fixture.
fn scratch(name: &str) -> PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.subsec_nanos())
        .unwrap_or(0);
    let dir = std::env::temp_dir().join(format!("{name}-{}-{nanos}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("create the fixture root");
    dir
}
